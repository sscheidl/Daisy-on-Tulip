#!/usr/bin/env python3
"""Single editable protocol source -> C++/MicroPython constants."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / "config/protocol.json").read_text())
assert 1 <= data["channel"] <= 16
assert len(data["notes"]) == len(data["note_names"]) == 16
assert all(0 <= n <= 127 for n in data["notes"])
ccs = [v for k, v in data.items() if k.startswith("cc_") and k != "cc_interval_ms"]
assert len(set(ccs)) == len(ccs) and all(0 <= n < 120 for n in ccs)
cpp = "// Generated by scripts/generate_protocol.py. Edit config/protocol.json.\n#pragma once\n#include <cstdint>\nnamespace piano { namespace config {\n"
py = "# Generated by scripts/generate_protocol.py. Edit config/protocol.json.\n"
for key, value in data.items():
    name = key.upper()
    py += name + " = " + repr(tuple(value) if isinstance(value, list) else value) + "\n"
    if isinstance(value, int):
        cpp += "constexpr unsigned " + name + " = " + str(value) + ";\n"
    elif key == "notes":
        cpp += "constexpr uint8_t NOTES[16] = {" + ", ".join(map(str, value)) + "};\n"
cpp += "}} // namespace piano::config\n"
for relative, content in (("daisy/include/protocol_config.h", cpp), ("tulip/daisy_toy_piano/config.py", py)):
    path = ROOT / relative
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != content:
            raise SystemExit("Generated file is stale: " + str(path))
    else:
        path.write_text(content)
